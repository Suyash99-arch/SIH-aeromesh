const makeAssetPaths = (missionId) => ({
  video: `/assets/missions/${missionId}/flight-video.mp4`,
  model: `/assets/missions/${missionId}/reconstruction-model.glb`,
  pointCloud: `/assets/missions/${missionId}/point-cloud.ply`,
  flightPath: `/assets/missions/${missionId}/flight-path.json`,
});

const warnDuplicateAssetPaths = (items) => {
  if (!import.meta.env.DEV) return;

  const paths = new Map();
  for (const item of items) {
    const assetList = [
      item?.assets?.video,
      item?.assets?.model,
      item?.assets?.pointCloud,
      item?.assets?.flightPath,
    ].filter(Boolean);

    for (const assetPath of assetList) {
      const current = paths.get(assetPath);
      if (current) {
        console.warn(
          `[AeroMesh] Duplicate asset path detected for missions "${current}" and "${item.id}": ${assetPath}`,
        );
      } else {
        paths.set(assetPath, item.id);
      }
    }
  }
};

